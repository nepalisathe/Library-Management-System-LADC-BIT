//// TEN * -- EXTRACTING TIME FROM COMPUTER AND CONVERT TO READY TO USE INTEGER
void get_year_mth_day(int *day, int *month, int *year) {
	time_t t = time(NULL);
	struct tm tm = *localtime(&t);
	
	*day = tm.tm_mday;
	*month = tm.tm_mon + 1;
	*year = tm.tm_year + 1900;
}

