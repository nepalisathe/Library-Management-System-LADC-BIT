//// SIX * -- COUNT EXISTING STU IN THE BATCH & RETURN NEXT SEQ. NUMBER
int get_next_seq_stu(int batch) {
    FILE *fp;
    fp = fopen("student.txt","r");
    if(fp == NULL) {
        anim_msg_on_demand( "PROGRAM IS RUNNING WITHOUT THE DATABASE ! Can't proceed...", 2000);   // DATABASE COULD NOT LOAD
        return 1;   // student file could not load again
    }

    struct student_list temp_stu;
    int count = 0, fields_read;
    while((fields_read = fscanf(fp," %12[^|]|%29[^|]|%d|%11[^|]|%d|%d|%7[^|]|%19[^|]|%29[^|]|%d|%d|%d",
                                																		temp_stu.stu_id,
																										temp_stu.stu_name,
																										&temp_stu.stu_batch,
																										temp_stu.program,
                                																		&temp_stu.stdy_sem,
																										&temp_stu.stdy_year,
																										temp_stu.gender,
																										temp_stu.phone,
																										temp_stu.addr,
                               																			&temp_stu.dob.year,
																										&temp_stu.dob.mth,
																										&temp_stu.dob.day)) == 12)
	{
        if(temp_stu.stu_batch == batch) {
            count++;
        }
    }
    
    fclose(fp);
    return count + 1;
}

//// SEVEN * -- BUILDS THE FORMATTED STUDENT ID FROM BATCH AND SEQUENCE
